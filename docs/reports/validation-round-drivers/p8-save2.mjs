import { newBrowser, newCtx, loginEmailPassword, shot, BASE } from '/private/tmp/claude-504/-Users-Cactai/7d466399-a5d3-4532-8719-eeb55a81f620/scratchpad/driver.mjs';
import fs from 'fs';
const env = JSON.parse(fs.readFileSync('/tmp/testenv.json','utf8'));
const b = await newBrowser(); const ctx = await newCtx(b); const p = await ctx.newPage();
const rpc=[]; p.on('request',r=>{const m=r.url().split('rpc/')[1]?.split('?')[0]; if(m&&/create_horse_record/.test(m))rpc.push(m);});
let createResp=null; p.on('response',async r=>{ if(r.url().includes('create_horse_record')){try{createResp={s:r.status(),t:(await r.text()).slice(0,150)};}catch{}} });
await loginEmailPassword(p, env.FHE_TEST_CLIENT_EMAIL, env.FHE_TEST_CLIENT_PASSWORD);
await p.goto(`${BASE}/app/horse-intake`,{waitUntil:'domcontentloaded'}); await p.waitForTimeout(4000);
await p.getByPlaceholder(/horse.s name/i).first().fill('VR Gate Horse');
await p.waitForTimeout(500);
const saveBtn = p.getByRole('button',{name:/Save my horse/i}).first();
await saveBtn.scrollIntoViewIfNeeded();
await saveBtn.click({timeout:15000});
await p.waitForTimeout(7000);
console.log('RPC fired:', JSON.stringify(rpc), '| resp:', JSON.stringify(createResp));
console.log('URL:', p.url());
const body = await p.evaluate(()=>document.body.innerText);
console.log('post-save:', body.split('\n').filter(l=>/saved|added|error|could not|unanswered|pending|to be provided/i.test(l)).slice(0,5));
await shot(p,'p8-02-horse-saved');
await b.close();
